export const LANGUAGES = ['en', 'cs'];

function detect() {
  const ui = globalThis.chrome?.i18n?.getUILanguage?.() || globalThis.navigator?.language || 'en';
  return /^(cs|sk)\b/i.test(ui) ? 'cs' : 'en';
}

let lang = detect();

export function setLanguage(choice) {
  lang = LANGUAGES.includes(choice) ? choice : detect();
  if (globalThis.document) document.documentElement.lang = lang;
}

export const language = () => lang;

export function t(id, params = {}) {
  const m = MESSAGES[lang][id] ?? MESSAGES.en[id];
  if (m === undefined) return id;
  if (typeof m === 'function') return m(params);
  if (typeof m !== 'string') return m;
  return m.replace(/\{(\w+)\}/g, (all, k) => (params[k] === undefined ? all : String(params[k])));
}

// A message to render later, e.g. in a stored conversion report.
export const msg = (id, params = {}) => ({ id, params });

export function fmt(m) {
  if (typeof m === 'string') return m;
  return m ? t(m.id, m.params) : '';
}

// Error carrying a message id, so it can be shown in any language.
export class LocalizedError extends Error {
  constructor(id, params = {}) {
    super(t(id, params));
    this.msg = msg(id, params);
  }
}

export function translatePage(root = document) {
  for (const el of root.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  for (const el of root.querySelectorAll('[data-i18n-title]')) el.title = t(el.dataset.i18nTitle);
  for (const el of root.querySelectorAll('[data-i18n-placeholder]')) el.placeholder = t(el.dataset.i18nPlaceholder);
}
